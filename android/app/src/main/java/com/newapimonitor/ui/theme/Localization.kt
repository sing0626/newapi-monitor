/** Structured templates keep interpolated alert bodies translated in all four languages. */
fun alertMessage(key: String, args: List<String>, language: String): String {
    val index = when (language) { "zh-TW" -> 1; "zh-CN" -> 2; "en" -> 3; else -> 0 }
    val template = alertTemplates[key]?.get(index) ?: return key
    return String.format(java.util.Locale.ROOT, template, *args.toTypedArray())
}

